'use client';
import { useState } from 'react';
import ToolLayout from '../../../../components/ToolLayout';
import { getToolById } from '../../../../lib/tools';
import { Copy, Check, Download, Bot } from 'lucide-react';

export default function RobotsTxtPage() {
  const tool = getToolById('robots-txt');
  const [allowAll, setAllowAll] = useState(true);
  const [disallowedPaths, setDisallowedPaths] = useState('/admin/\n/api/\n/private/');
  const [sitemapUrl, setSitemapUrl] = useState('https://example.com/sitemap.xml');
  const [crawlDelay, setCrawlDelay] = useState(0);
  const [copied, setCopied] = useState(false);

  const paths = disallowedPaths.split('\n').map(p => p.trim()).filter(Boolean);

  const generatedTxt = `# robots.txt generated by UtilityHub
User-agent: *
${allowAll ? 'Allow: /' : 'Disallow: /'}
${paths.map(p => `Disallow: ${p}`).join('\n')}
${crawlDelay > 0 ? `Crawl-delay: ${crawlDelay}\n` : ''}
# AI Search and Crawlers
User-agent: GPTBot
Disallow: /private/

User-agent: ClaudeBot
Disallow: /private/

# Sitemap reference
Sitemap: ${sitemapUrl}`;

  const copy = () => {
    navigator.clipboard.writeText(generatedTxt);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  };

  const downloadTxt = () => {
    const blob = new Blob([generatedTxt], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'robots.txt';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <ToolLayout tool={tool} category="seo">
      <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))', gap: 24 }}>
        <div className="tool-panel">
          <div className="tool-panel-header"><span>Crawl Rules</span></div>
          <div className="tool-panel-body">
            <label style={{ display: 'flex', alignItems: 'center', gap: 8, cursor: 'pointer', marginBottom: 16 }}>
              <input
                type="checkbox"
                checked={allowAll}
                onChange={(e) => setAllowAll(e.target.checked)}
              />
              <span style={{ fontWeight: 600, fontSize: '0.9rem' }}>Allow all search engines by default (Allow: /)</span>
            </label>

            <div>
              <label className="form-label">Disallowed Paths (one per line)</label>
              <textarea
                className="form-textarea"
                style={{ fontFamily: 'var(--font-mono)', fontSize: '0.85rem' }}
                rows={5}
                value={disallowedPaths}
                onChange={(e) => setDisallowedPaths(e.target.value)}
              />
            </div>

            <div style={{ marginTop: 16 }}>
              <label className="form-label">Sitemap URL</label>
              <input
                type="text"
                className="form-input"
                value={sitemapUrl}
                onChange={(e) => setSitemapUrl(e.target.value)}
              />
            </div>

            <div style={{ marginTop: 16 }}>
              <label className="form-label">Crawl Delay (seconds, 0 for none): {crawlDelay}s</label>
              <input
                type="range"
                min="0"
                max="30"
                value={crawlDelay}
                onChange={(e) => setCrawlDelay(Number(e.target.value))}
                style={{ width: '100%' }}
              />
            </div>
          </div>
        </div>

        {/* Output */}
        <div className="tool-panel">
          <div className="tool-panel-header" style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center' }}>
            <span>Generated robots.txt</span>
            <div style={{ display: 'flex', gap: 8 }}>
              <button className={`btn btn-sm ${copied ? 'btn-copy copied' : 'btn-secondary'}`} onClick={copy}>
                {copied ? <Check size={14} /> : <Copy size={14} />}
                {copied ? 'Copied' : 'Copy'}
              </button>
              <button className="btn btn-primary btn-sm" onClick={downloadTxt}>
                <Download size={14} /> Download
              </button>
            </div>
          </div>
          <div className="tool-panel-body">
            <textarea
              className="form-textarea"
              style={{ fontFamily: 'var(--font-mono)', fontSize: '0.8rem' }}
              rows={14}
              value={generatedTxt}
              readOnly
            />
          </div>
        </div>
      </div>
    </ToolLayout>
  );
}
